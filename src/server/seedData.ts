function formatStorageLabel(s: string): string {
  return s.replace(/(\d+)\s*(GB|TB)/i, '$1 $2').toUpperCase().trim();
}

function formatRamLabel(r: string): string {
  const match = r.match(/(\d+)\s*GB/i);
  if (match) return `${match[1]} GB`;
  return r.trim();
}

